/** 把「AI 帮我选」翻译成一句让模型自己判断的指令，而不是丢弃这一项 */
function orAuto(label, id, selfTask) {
  return id === 'auto' ? `AI 帮我选（这一项由${selfTask}）` : label;
}

function subjectText(sel) {
  const label = T.subjectLabel(sel.topic, sel.subject);
  if (sel.subject === 'auto' || !label) {
    return 'AI 帮我选（你自己根据上面的大方向判断具体拍什么）';
  }
  return label;
}

function subjectHint(sel) {
  return SUBJECT_HINT[sel.subject] || '';
}

/** 拼「这次的选择」区块 —— 这是模型能拿到的全部信息 */
function selectionBlock(sel) {
  const lines = [
    `【大方向】${sel.topic === 'auto' ? 'AI 帮我选（你自己判断今天这条拍什么方向最合适）' : T.topicLabel(sel.topic)}`,
    `【具体拍什么】${subjectText(sel)}`,
    `【这条想让顾客干什么】${orAuto(T.goalLabel(sel.goal), sel.goal, '你自己判断这条视频最该让顾客做什么')}`,
    `【谁出镜】${orAuto(T.speakerLabel(sel.speaker), sel.speaker, '你自己判断谁出镜最合适')}`,
    `【怎么说】${orAuto(T.toneLabel(sel.tone), sel.tone, '你自己判断哪种语气最合适')}`,
    `【时长】${sel.duration} 秒 → ${SENTENCE_HINT[sel.duration]}，正文汉字数落在 ${T.DURATION_WORDS[sel.duration]} 之间`
  ];
  return lines.join('\n');
}

/** 拼「写作要求」区块 —— 只把被选中的策略带进来，不是全塞 */
function strategyBlock(sel) {
  const parts = [];

  const goal = GOAL_STRATEGY[sel.goal];
  if (goal) parts.push('【这条视频的目标 —— 怎么写】\n' + goal);

  const speaker = SPEAKER_STRATEGY[sel.speaker];
  if (speaker) parts.push('【出镜人 —— 口吻怎么写】\n' + speaker);

  const tone = TONE_STRATEGY[sel.tone];
  if (tone) parts.push('【语气 —— 怎么说话】\n' + tone);

  const hint = subjectHint(sel);
  if (hint) parts.push('【内容方向】\n' + hint);

  // 「学一个穿搭方法」「解决一个穿衣问题」这两类，给一点真正能用的原料
  if (sel.goal === 'learntips' || sel.goal === 'solveproblem') {
    parts.push(`【可以用的行业通用方法（只是思路，不是让你照抄）】
· 先看身形：肩宽、身高、上下身比例，决定版型往哪个方向选
· 再看场合：通勤、约会、休闲，同一件衣服不同搭法差别很大
· 一定要摸面料：捏一下看回弹，看会不会起球、透不透
· 试穿要做几个动作：抬手、坐下、转身，看会不会绷
· 基础款太多的时候，不用急着买新的，先换掉三个地方：鞋、包、外搭

【顾客最常见的坑（可以拿来当痛点，但不要编具体产品）】
· 只看图片下单，到手发现色差和垂坠感完全不一样
· 不看面料，穿两次就起球变形
· 尺码按平时穿的买，没试就下单，肩线不对
· 只图便宜，忽略版型，穿一次就压箱底
· 买了一堆，但互相搭不起来，还是没得穿`);
  }

  return parts.join('\n\n');
}

